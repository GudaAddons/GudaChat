-- Whisper icon model: people with unread whispers, newest-first order, the limit of 10,
-- the "latest" person, read on a sent whisper, Battle.net vs character keys, secret
-- values, and the whisper ring geometry and tap detection

local function Receive(model, sender, text, extra)
    local info = { sender = sender, text = text, time = 100, display = sender }
    for key, value in pairs(extra or {}) do info[key] = value end
    return model:Receive(info)
end

return function(T, H)
    local ns = H.Load()

    T.case("the badge counts people, not messages", function()
        local model = ns.NewWhisperModel()
        Receive(model, "Jaina", "hi")
        Receive(model, "Jaina", "you there?")
        Receive(model, "Thrall", "hello")
        T.eq(model:UnreadCount(), 2)
        T.eq(#model:Get("pc:jaina").lines, 2, "both lines kept")
    end)

    T.case("the list is newest first", function()
        local model = ns.NewWhisperModel()
        Receive(model, "Jaina", "1")
        Receive(model, "Thrall", "2")
        Receive(model, "Uther", "3")
        Receive(model, "Jaina", "4")
        local list = model:List()
        T.eq(list[1].display, "Jaina")
        T.eq(list[2].display, "Uther")
        T.eq(list[3].display, "Thrall")
        T.eq(list[1].last, "4", "last message")
    end)

    T.case("only the 10 most recent people are kept", function()
        local model = ns.NewWhisperModel()
        for i = 1, 12 do
            Receive(model, "Player" .. string.char(64 + i), "hi")
        end
        local list = model:List()
        T.eq(#list, 10)
        T.eq(model:Get("pc:playera"), nil, "oldest dropped")
        T.eq(model:Get("pc:playerb"), nil, "second oldest dropped")
        T.ok(model:Get("pc:playerl") ~= nil, "newest kept")
    end)

    T.case("conversations keep the last 5 lines", function()
        local model = ns.NewWhisperModel()
        for i = 1, 7 do Receive(model, "Jaina", "line" .. i) end
        local lines = model:Get("pc:jaina").lines
        T.eq(#lines, 5)
        T.eq(lines[1].text, "line3")
        T.eq(lines[5].text, "line7")
    end)

    T.case("latest is the newest unread, else the newest", function()
        local model = ns.NewWhisperModel()
        Receive(model, "Jaina", "a")
        Receive(model, "Thrall", "b")
        model:MarkRead("pc:thrall")
        T.eq(model:Latest().display, "Jaina", "newest unread")
        model:MarkRead("pc:jaina")
        T.eq(model:Latest().display, "Thrall", "newest when all read")
        T.eq(ns.NewWhisperModel():Latest(), nil, "empty")
    end)

    T.case("whispering someone marks them read and adds the line", function()
        local model = ns.NewWhisperModel()
        Receive(model, "Jaina-Realm", "hi")
        local person = model:Sent("Jaina-Realm", nil, "on my way", 120)
        T.ok(person ~= nil, "found")
        T.eq(person.unread, false)
        T.eq(model:UnreadCount(), 0)
        T.eq(person.lines[2].out, true)
        T.eq(person.lines[2].text, "on my way")
        T.eq(model:Sent("Stranger", nil, "hi", 130), nil, "unknown target ignored")
    end)

    T.case("realm and case do not split one person", function()
        local model = ns.NewWhisperModel()
        Receive(model, "Jaina-Realm", "a")
        Receive(model, "jaina", "b")
        T.eq(#model:List(), 1)
        T.eq(model:Get("pc:jaina").target, "jaina", "reply goes to the last name shape")
    end)

    T.case("Forever two-part names meet in every shape", function()
        local model = ns.NewWhisperModel()
        Receive(model, "Joob Stabber", "a")
        Receive(model, "JoobStabber", "b")
        Receive(model, "joob stabber-Realm", "c")
        T.eq(#model:List(), 1)
        T.eq(ns.WhisperKey("Joob Stabber"), "pc:joobstabber")
        model:Sent("Joob Stabber", nil, "hey", 200)
        T.eq(model:UnreadCount(), 0)
    end)

    T.case("Battle.net friends are keyed by account id", function()
        local model = ns.NewWhisperModel()
        Receive(model, "|Kq1|k", "hi", { bnAccountID = 42, display = "Rexxar#2147" })
        Receive(model, "|Kq2|k", "again", { bnAccountID = 42, display = "Rexxar#2147" })
        Receive(model, "Rexxar", "a character", nil)
        T.eq(#model:List(), 2, "friend and character apart")
        local friend = model:Get("bn:42")
        T.eq(friend.display, "Rexxar#2147")
        T.eq(#friend.lines, 2)
        model:Sent(nil, 42, "reply", 300)
        T.eq(friend.unread, false, "BN reply marks read")
    end)

    T.case("secret values are never stored", function()
        local model = ns.NewWhisperModel()
        T.eq(Receive(model, H.SECRET, "hi"), nil, "secret sender ignored")
        T.eq(Receive(model, "|Kq1|k", "hi", { bnAccountID = H.SECRET }), nil, "secret account id ignored")
        local person = Receive(model, "Jaina", H.SECRET)
        T.ok(person ~= nil, "secret message still counts")
        T.eq(person.last, nil, "no text kept")
        T.eq(person.lines[1].text, nil, "no line text")
        T.eq(model:UnreadCount(), 1)
    end)

    T.case("the ring lists unread first, at most 8", function()
        local model = ns.NewWhisperModel()
        for i = 1, 10 do Receive(model, "Player" .. string.char(64 + i), "hi") end
        for _, key in ipairs({ "pc:playerj", "pc:playeri", "pc:playerh", "pc:playerg" }) do
            model:MarkRead(key)
        end
        local ring = model:RingList()
        T.eq(#ring, 8)
        T.eq(ring[1].display, "PlayerF", "newest unread first")
        T.ok(ring[1].unread and ring[6].unread, "unread group")
        T.eq(ring[7].display, "PlayerJ", "read ones after, newest first")
        T.eq(ring[8].display, "PlayerI", "cut at 8")
    end)

    T.case("ring slots start at the top and go clockwise", function()
        local x, y = ns.RingSlotOffset(1, 4, 100)
        T.ok(math.abs(x) < 1e-9 and math.abs(y - 100) < 1e-9, "slot 1 top")
        x, y = ns.RingSlotOffset(2, 4, 100)
        T.ok(math.abs(x - 100) < 1e-9 and math.abs(y) < 1e-9, "slot 2 right")
        T.eq(ns.RingSlotAt(0, 50, 4, 20), 1, "up")
        T.eq(ns.RingSlotAt(50, 0, 4, 20), 2, "right")
        T.eq(ns.RingSlotAt(0, -50, 4, 20), 3, "down")
        T.eq(ns.RingSlotAt(-50, 0, 4, 20), 4, "left")
        T.eq(ns.RingSlotAt(30, 40, 8, 20), 2, "between up and right, 8 slots")
        T.eq(ns.RingSlotAt(-5, 60, 8, 20), 1, "just left of the top")
    end)

    T.case("the ring centre and an empty ring pick nobody", function()
        T.eq(ns.RingSlotAt(5, 5, 6, 20), nil, "centre")
        T.eq(ns.RingSlotAt(50, 50, 0, 20), nil, "no slots")
    end)

    T.case("a short still press is a tap", function()
        T.ok(ns.IsRingTap(0.1, 2), "tap")
        T.ok(not ns.IsRingTap(0.5, 2), "held")
        T.ok(not ns.IsRingTap(0.1, 20), "moved")
    end)
end
